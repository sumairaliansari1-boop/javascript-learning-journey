// ****** Addition Number **********

function additionNumber(val1,val2){
   return  val1 + val2 
}


console.log(additionNumber(22,32))



// ******* Substraction Function ********

function susbsNumber(num1,num2){
    return num1 - num2
  
}

console.log(susbsNumber(30,14))





